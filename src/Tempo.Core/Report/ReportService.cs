using System.Text;
using Tempo.Core.Models;

namespace Tempo.Core.Report;

/// <summary>Builds a self-contained HTML system report the user can save/share.</summary>
public class ReportService
{
    public string BuildHtml(SystemInfo si, List<OptimizationItem> opts, List<BackupSession> history)
    {
        string E(string? s) => System.Net.WebUtility.HtmlEncode(s ?? "");
        string Gb(long b) => (b / 1073741824.0).ToString("0.#") + " GB";

        var sb = new StringBuilder();
        sb.Append("<!doctype html><html><head><meta charset='utf-8'><title>Tempo System Report</title><style>");
        sb.Append("body{font-family:Segoe UI,Arial,sans-serif;background:#0d1117;color:#d7dde6;margin:0;padding:32px;}");
        sb.Append("h1{color:#fff;font-size:24px}h2{color:#7ee0a3;font-size:16px;margin-top:28px;border-bottom:1px solid #222b36;padding-bottom:6px}");
        sb.Append("table{border-collapse:collapse;width:100%;font-size:13px}td,th{text-align:left;padding:6px 10px;border-bottom:1px solid #1b2430}th{color:#8b97a6;font-weight:600}");
        sb.Append(".muted{color:#8b97a6}.ok{color:#7ee0a3}.warn{color:#ffb454}.bad{color:#ff6b6b}");
        sb.Append("</style></head><body>");
        sb.Append("<h1>Tempo System Report</h1><div class='muted'>").Append(E(si.MachineName))
          .Append(" &middot; generated ").Append(DateTime.Now.ToString("yyyy-MM-dd HH:mm")).Append("</div>");

        sb.Append("<h2>Hardware</h2><table>");
        sb.Append("<tr><th>CPU</th><td>").Append(E(si.Cpu.Name)).Append(" (").Append(si.Cpu.Cores).Append("C/").Append(si.Cpu.Threads).Append("T)</td></tr>");
        foreach (var g in si.Gpus)
            sb.Append("<tr><th>GPU</th><td>").Append(E(g.Name))
              .Append(g.VramBytes > 0 ? " — " + Gb(g.VramBytes) + " VRAM" : "")
              .Append(" — driver ").Append(E(g.DriverVersion))
              .Append(g.DriverAgeDays >= 0 ? " (" + g.DriverAgeDays + " days old)" : "")
              .Append(g.Resolution.Length > 0 ? " — " + E(g.Resolution) + "@" + g.RefreshRate + "Hz" : "")
              .Append("</td></tr>");
        sb.Append("<tr><th>RAM</th><td>").Append(Gb(si.Ram.TotalBytes)).Append(" (").Append(si.Ram.Sticks)
          .Append(" stick(s), ").Append(si.Ram.SpeedMhz).Append(" MT/s, ").Append(E(si.Ram.Channels)).Append(")</td></tr>");
        foreach (var d in si.Drives)
            sb.Append("<tr><th>Drive ").Append(E(d.Letter)).Append("</th><td>")
              .Append(E(d.MediaType)).Append(" — ").Append(Gb(d.FreeBytes)).Append(" free of ").Append(Gb(d.TotalBytes))
              .Append(" — health: ").Append(E(d.Health)).Append(d.IsSystemDrive ? " (system)" : "").Append("</td></tr>");
        sb.Append("<tr><th>Motherboard</th><td>").Append(E(si.Motherboard)).Append("</td></tr>");
        sb.Append("<tr><th>OS</th><td>").Append(E(si.Os.Name)).Append(" ").Append(E(si.Os.DisplayVersion))
          .Append(" (build ").Append(E(si.Os.Build)).Append(") ").Append(E(si.Os.Edition)).Append("</td></tr>");
        sb.Append("<tr><th>Power plan</th><td>").Append(E(si.ActivePowerPlan)).Append("</td></tr>");
        sb.Append("<tr><th>Type</th><td>").Append(si.IsLaptop ? "Laptop" : "Desktop").Append("</td></tr>");
        sb.Append("</table>");

        sb.Append("<h2>Optimization status</h2><table><tr><th>Optimization</th><th>Status</th><th>Impact</th></tr>");
        foreach (var o in opts.Where(o => o.Available && o.Kind == "setting"))
            sb.Append("<tr><td>").Append(E(o.Title)).Append("</td><td class='")
              .Append(o.Applied ? "ok'>applied" : "muted'>not applied").Append("</td><td>").Append(E(o.Impact)).Append("</td></tr>");
        sb.Append("</table>");

        if (history.Count > 0)
        {
            sb.Append("<h2>Change history</h2><table><tr><th>When</th><th>Change</th><th>Status</th></tr>");
            foreach (var s in history.Take(20))
                foreach (var c in s.Changes)
                    sb.Append("<tr><td class='muted'>").Append(c.At.ToString("yyyy-MM-dd HH:mm")).Append("</td><td>")
                      .Append(E(c.Title)).Append("</td><td>").Append(c.Restored ? "<span class='warn'>restored</span>" : "<span class='ok'>active</span>").Append("</td></tr>");
            sb.Append("</table>");
        }

        sb.Append("<div class='muted' style='margin-top:30px'>Generated by Tempo — free &amp; open gaming optimizer. No data leaves this PC.</div>");
        sb.Append("</body></html>");
        return sb.ToString();
    }
}
